// Render results/*.json as results/RESULTS.md (one table per kernel file).
import {readFileSync, writeFileSync, readdirSync} from 'node:fs';

const dir = new URL('./results/', import.meta.url);
const files = ['k-hash', 'k-field', 'k-gf128', 'k-blake2s', 'k-rpo', 'k-tip5', 'k-stark'].filter((f) => readdirSync(dir).includes(f + '.json'));
const n = (x) => Math.round(x).toLocaleString('en-US');
const rng = (a) => (Math.round(a.min) === Math.round(a.max) ? n(a.mean) : `${n(a.mean)} (${n(a.min)}–${n(a.max)})`);
const titles = {
  'k-hash': 'Hashing and Merkle (K5, K6, K7, K8, K17)', 'k-field': 'Field arithmetic (K1, K2, K19, comparison fields)',
  'k-gf128': 'GF(2^128) multiplication (K15)', 'k-blake2s': 'Blake2s compression (K16)', 'k-rpo': 'RPO permutation (K16) and K4 chain',
  'k-tip5': 'Tip5 permutation (K16)', 'k-stark': 'STARK steps (K3, K4, K9, K10, K11, K12, K13, K14)',
};
let out = '# pq-hash kernel measurements (generated by table.mjs from results/*.json)\n\n' +
  'libauth 3.1.0-next.8, BCH_2026 instruction set. Op-cost per call: mean over random trials (min–max). ' +
  '"std" uses 192 per hash digest iteration, "cons" 64. "code" = measured bytecode bytes (+ function bodies defined in the prologue). ' +
  '"real VM" = the case also passed the real BCH 2026 VM (standard and consensus) as a P2SH32 spend padded to cover its op-cost; ' +
  '"over" = the padded spend would exceed one standard input (10,000 B), measured on the loosened VM only.\n';
for (const f of files) {
  const rows = JSON.parse(readFileSync(new URL(f + '.json', dir), 'utf8'));
  out += `\n## ${titles[f] ?? f}\n\n| id | kernel | op-cost std | op-cost cons | hash iter | code B | BCHN-adjusted | real VM | notes |\n|---|---|--:|--:|--:|--:|---|---|---|\n`;
  for (const r of rows) {
    const code = `${n(r.bodyBytes.max)}${r.defBytes ? ' + ' + n(r.defBytes) : ''}`;
    const bchn = r.extra?.bchnExtra ? `${n(r.opStd.mean + r.extra.bchnExtra)} (+${n(r.extra.bchnExtra)} at OP_DEFINE)`
      : r.defBytes ? `define once: libauth ${n(r.defineLibauth)}, BCHN ${n(r.defineBchn)}` : '= libauth';
    let notes = r.notes ?? '';
    if (r.extra?.subtract) notes += ` [net of cleanup: ${n(r.opStd.mean - r.extra.subtract)} std]`;
    if (r.extra?.perLevel) notes += ` [per level: ${n(r.opStd.mean / r.extra.perLevel)} std, ${n(r.opCons.mean / r.extra.perLevel)} cons]`;
    if (r.extra?.perIter) notes += ` [per unit: ${n(r.opStd.mean / r.extra.perIter)}]`;
    if (r.perNodeStd) notes += ` [nodes ${n(r.nodes.mean)}; per node ${n(r.perNodeStd.mean)} std, ${n(r.perNodeCons.mean)} cons]`;
    const real = r.real.map((x) => (x === 'ok' ? 'ok' : x === 'over one standard input' ? 'over' : x)).join('; ');
    out += `| ${r.id} | ${r.name} | ${rng(r.opStd)} | ${rng(r.opCons)} | ${rng(r.iters)} | ${code} | ${bchn} | ${real} | ${notes.trim()} |\n`;
  }
}
writeFileSync(new URL('RESULTS.md', dir), out);
console.log('wrote results/RESULTS.md');

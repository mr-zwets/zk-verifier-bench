import json,sys
o=json.load(open(sys.argv[1]))
cls={}
def c(op):
    if op<=0x60 and op!=0x4f: return 'push/const'
    if op in (0x8a,):return 'OP_INVOKE'
    if op==0x89: return 'OP_DEFINE'
    if op in (0x95,0x96,0x97,0x93,0x94,0x8b,0x8c,0x8f,0x90,0x92,0xa3,0xa4,0xa5,0x8d,0x8e):
        return {0x95:'MUL',0x96:'DIV',0x97:'MOD',0x93:'ADD',0x94:'SUB'}.get(op,'other arith/cmp')
    if 0x6b<=op<=0x7d or op in (0x6d,0x6e,0x6f,0x70,0x71,0x72,0x73,0x74,0x75,0x76,0x77,0x78,0x79,0x7a,0x7b,0x7c,0x7d): return 'stack shuffle'
    if op in (0x63,0x64,0x67,0x68,0x65,0x66,0x69): return 'control/verify'
    if op in (0x9c,0x9d,0x9e,0x9f,0xa0,0xa1,0xa2,0x87,0x88,0x9a,0x9b,0x91): return 'other arith/cmp'
    if op in (0x7e,0x7f,0x80,0x81,0x82,0x83,0x84,0x85,0x86,0x80): return 'bytes (cat/split/size/bin2num)'
    if op in (0xa8,0xa9,0xaa,0xa6,0xa7): return 'hash'
    return 'other %x'%op
for op,v in o['byOpcode']:
    k=c(int(op)); cls[k]=cls.get(k,0)+v
tot=sum(cls.values())
print('instr',o.get('instr'),'arith',o.get('arith'),'pushed',o.get('pushed'),'base',o.get('instr',0)*100,'total',tot)
for k,v in sorted(cls.items(),key=lambda x:-x[1]): print('  %-34s %9.3fM %5.1f%%'%(k,v/1e6,100*v/tot))
